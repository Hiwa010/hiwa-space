export const getFrameUrl = (frameIndex: number): string => {
  const clamped = Math.max(0, Math.min(TOTAL_WEBP_FRAMES - 1, Math.floor(frameIndex)));
  const paddedIndex = String(clamped).padStart(3, '0');
  return `${WEBP_BASE_URL}/frame_${paddedIndex}_delay-0.042s.webp`;
};

